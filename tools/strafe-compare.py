#!/usr/bin/env python3
"""Compare air-strafe acceleration between Xonotic and Vortex Arena from console logs.

Both engines print one parseable line per landing when `speedmeter 1` and `developer 1` are set:

    landing velocity: '412.093750 -88.312500 -264.000000' (abs: 500.164062)

Xonotic emits it from sys_phys_land (ecs/systems/sv_physics.qc:119-128); Vortex Arena emits it from the
same point in the ground branch (PlayerPhysics.SpeedMeterPrint, wired in GameWorld). The capture scripts
generated by StrafeBotHarness bracket each turn-rate leg with

    STRAFE-BEGIN <yawspeed>   ...   STRAFE-END

so this script can attribute each landing to the cl_yawspeed it was produced at, and diff the two engines
leg by leg.

Only the HORIZONTAL speed is compared. The logged vector's z component is the (negative) fall speed at the
landing instant, which depends on exactly where in the arc the landing tick fell and is therefore noisy in
a way the horizontal speed is not.

Usage
-----
    # generate the capture scripts + the offline reference sweep
    dotnet test tests/VortexArena.Tests/VortexArena.Tests.csproj \
        --filter FullyQualifiedName~StrafeBotHarness

    # ... run both games with the generated .cfg files, then:
    python tools/strafe-compare.py --xonotic ~/.xonotic/data/qconsole.log \
                                   --vortex  _scratch/vortex-console.log \
                                   --sim     _scratch/strafe/vortex-yawsweep.csv
"""

from __future__ import annotations

import argparse
import csv
import math
import re
import sys
from pathlib import Path

# "landing velocity: '<x> <y> <z>' (abs: <n>)" — Base's LOG_TRACEF text, matched loosely enough to survive
# a console colour prefix or a timestamp in front of it.
LANDING_RE = re.compile(
    r"landing velocity:\s*'\s*(-?[\d.eE+]+)\s+(-?[\d.eE+]+)\s+(-?[\d.eE+]+)\s*'"
)
# The markers the generated capture scripts echo around each leg. "^3"/"^2" are Quake colour codes.
BEGIN_RE = re.compile(r"STRAFE-BEGIN\s+(\d+)")
END_RE = re.compile(r"STRAFE-END")


def parse_log(path: Path) -> dict[int, list[float]]:
    """Return {yawspeed: [horizontal landing speed, ...]} from one engine's console log."""
    legs: dict[int, list[float]] = {}
    current: int | None = None
    with path.open("r", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            begin = BEGIN_RE.search(line)
            if begin:
                current = int(begin.group(1))
                legs.setdefault(current, [])
                continue
            if END_RE.search(line):
                current = None
                continue
            hit = LANDING_RE.search(line)
            if hit and current is not None:
                vx, vy = float(hit.group(1)), float(hit.group(2))
                legs[current].append(math.hypot(vx, vy))
    return legs


def parse_sim(path: Path) -> dict[int, float]:
    """Return {yawspeed: bhop_end_speed} from the offline harness CSV."""
    out: dict[int, float] = {}
    with path.open("r", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            out[int(float(row["yaw_deg_per_s"]))] = float(row["bhop_end_speed"])
    return out


def leg_speed(samples: list[float]) -> float | None:
    """One number per leg: the LAST landing, i.e. the speed the leg converged to.

    The capture scripts release +jump at the end of the window, so the final landing is the one that
    actually reaches the ground branch and gets logged. Earlier entries (if any) come from hops that
    happened to break the autohop chain and are kept only for the sample count.
    """
    return samples[-1] if samples else None


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--xonotic", type=Path, help="Xonotic qconsole.log (launch with -condebug)")
    ap.add_argument("--vortex", type=Path, help="Vortex Arena console log")
    ap.add_argument("--sim", type=Path, help="vortex-yawsweep.csv from StrafeBotHarness")
    ap.add_argument("--tolerance", type=float, default=5.0,
                    help="u/s difference treated as agreement (default 5)")
    args = ap.parse_args()

    if not any([args.xonotic, args.vortex, args.sim]):
        ap.print_help()
        return 2

    xon = parse_log(args.xonotic) if args.xonotic else {}
    vor = parse_log(args.vortex) if args.vortex else {}
    sim = parse_sim(args.sim) if args.sim else {}

    for name, path, data in (("xonotic", args.xonotic, xon), ("vortex", args.vortex, vor)):
        if path and not data:
            print(f"warning: no STRAFE-BEGIN/landing pairs found in {path}.\n"
                  f"         check the run used the generated .cfg, and that both `speedmeter 1` and\n"
                  f"         `developer 1` were set (Base logs the line at LOG_TRACE).", file=sys.stderr)

    rates = sorted(set(xon) | set(vor) | set(sim))
    if not rates:
        print("nothing to compare", file=sys.stderr)
        return 1

    print(f"{'yaw deg/s':>10} {'xonotic':>10} {'vortex':>10} {'delta':>9} {'ratio':>7} {'sim':>10}")
    print("-" * 62)

    worst_delta = 0.0
    worst_rate = None
    deltas: list[float] = []
    for rate in rates:
        x = leg_speed(xon.get(rate, []))
        v = leg_speed(vor.get(rate, []))
        s = sim.get(rate)

        xs = f"{x:10.1f}" if x is not None else f"{'-':>10}"
        vs = f"{v:10.1f}" if v is not None else f"{'-':>10}"
        ss = f"{s:10.1f}" if s is not None else f"{'-':>10}"

        if x is not None and v is not None:
            d = v - x
            deltas.append(d)
            if abs(d) > abs(worst_delta):
                worst_delta, worst_rate = d, rate
            ds, rs = f"{d:+9.1f}", f"{v / x:7.3f}" if x else f"{'-':>7}"
        else:
            ds, rs = f"{'-':>9}", f"{'-':>7}"

        print(f"{rate:>10} {xs} {vs} {ds} {rs} {ss}")

    print()
    if deltas:
        mean = sum(deltas) / len(deltas)
        print(f"legs compared: {len(deltas)}   mean delta {mean:+.1f} u/s   "
              f"worst {worst_delta:+.1f} u/s at {worst_rate} deg/s")
        if abs(worst_delta) <= args.tolerance:
            print(f"VERDICT: engines agree within {args.tolerance:.0f} u/s at every turn rate.")
            print("         The difference players report is NOT in the acceleration path;")
            print("         look at the input layer (degrees per mouse count, m_smoothdt) instead.")
        else:
            sign = "FASTER" if mean > 0 else "SLOWER"
            print(f"VERDICT: Vortex Arena is {sign} than Xonotic by {abs(mean):.1f} u/s on average.")
            print(f"         Reproducer: cl_yawspeed {worst_rate}, hold +moveright +left +jump.")
            print("         Feed that turn rate to StrafeBotHarness and bisect the air branch.")
    else:
        print("no leg had data from both engines; nothing to diff")
    return 0


if __name__ == "__main__":
    sys.exit(main())
